const port = process.env.WMS_MINI_CDP_PORT ?? '9229';
const page = (await fetch(`http://127.0.0.1:${port}/json`).then((response) => response.json())).find((item) => item.type === 'page' && item.url.startsWith('https://localhost'));
if (!page) throw new Error('WMS-Mini WebView was not found.');
const socket = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, { once: true }); socket.addEventListener('error', reject, { once: true }); });
let id = 0;
const pending = new Map();
socket.addEventListener('message', (event) => { const message = JSON.parse(event.data); if (!message.id || !pending.has(message.id)) return; const request = pending.get(message.id); pending.delete(message.id); message.error ? request.reject(new Error(message.error.message)) : request.resolve(message.result); });
const command = (method, params = {}) => new Promise((resolve, reject) => { const requestId = ++id; pending.set(requestId, { resolve, reject }); socket.send(JSON.stringify({ id: requestId, method, params })); });
const evaluate = async (expression) => { const result = await command('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true }); if (result.exceptionDetails) throw new Error(result.exceptionDetails.text); return result.result.value; };
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const readState = () => evaluate(`new Promise((resolve, reject) => { const open=indexedDB.open('aardvarkland-mini-wms'); open.onsuccess=()=>{const get=open.result.transaction('state').objectStore('state').get('warehouse');get.onsuccess=()=>resolve(get.result);get.onerror=()=>reject(get.error)};open.onerror=()=>reject(open.error) })`);

await evaluate(`localStorage.setItem('aardvarkland-mini-language', 'cs')`);
await command('Page.reload'); await wait(700);
await evaluate(`document.querySelectorAll('.mobile-nav button')[4].click()`); await wait(250);
const original = await readState();
const marker = `QA restore ${Date.now()}`;
const importResult = await evaluate(`(() => {
  const input=document.querySelector('input[type=file]');
  const backup=${JSON.stringify({ marker: true })};
  const current=${JSON.stringify(original)};
  current.warehouseName=${JSON.stringify(marker)};
  const transfer=new DataTransfer(); transfer.items.add(new File([JSON.stringify(current)], 'valid-backup.json', {type:'application/json'}));
  input.files=transfer.files; input.dispatchEvent(new Event('change', {bubbles:true})); return true;
})()`);
await wait(600);
const restored = await readState();
const beforeCorrupt = JSON.stringify(restored);
await evaluate(`(() => { const input=document.querySelector('input[type=file]'); const transfer=new DataTransfer(); transfer.items.add(new File(['{"schemaVersion":99}'], 'corrupt.json', {type:'application/json'})); input.files=transfer.files; input.dispatchEvent(new Event('change', {bubbles:true})); })()`);
await wait(500);
const corruptToast = await evaluate(`document.querySelector('[role=status]')?.textContent ?? ''`);
const afterCorrupt = await readState();
await evaluate(`(() => { const input=document.querySelector('input[type=file]'); const transfer=new DataTransfer(); transfer.items.add(new File([${JSON.stringify(JSON.stringify(original))}], 'restore-original.json', {type:'application/json'})); input.files=transfer.files; input.dispatchEvent(new Event('change', {bubbles:true})); })()`);
await wait(500);
const finalState = await readState();
const report = { importTriggered: importResult, validImportApplied: restored.warehouseName === marker, corruptImportRejected: JSON.stringify(afterCorrupt) === beforeCorrupt && corruptToast.includes('platná'), originalRestored: JSON.stringify(finalState) === JSON.stringify(original) };
report.ok = Object.values(report).every(Boolean);
console.log(JSON.stringify(report, null, 2));
socket.close();
process.exitCode = report.ok ? 0 : 1;
